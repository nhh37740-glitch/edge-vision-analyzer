const std::uint8_t* glyph_for(char c) {
  const unsigned char uc = static_cast<unsigned char>(c);
  if (uc < 0x20 || uc > 0x7E) {
    return kFont8x8['?' - 0x20];
  }
  return kFont8x8[uc - 0x20];
}

void put_pixel(std::vector<std::uint8_t>& dst, int width, int height, int x,
               int y, const std::uint8_t color[3]) {
  if (x < 0 || x >= width || y < 0 || y >= height) {
    return;
  }
  const std::size_t index =
      (static_cast<std::size_t>(y) * static_cast<std::size_t>(width) +
       static_cast<std::size_t>(x)) *
      3;
  dst[index] = color[0];
  dst[index + 1] = color[1];
  dst[index + 2] = color[2];
}

void fill_rect(std::vector<std::uint8_t>& dst, int width, int height, int x0,
               int y0, int x1, int y1, const std::uint8_t color[3]) {
  for (int y = y0; y <= y1; ++y) {
    for (int x = x0; x <= x1; ++x) {
      put_pixel(dst, width, height, x, y, color);
    }
  }
}

void draw_box(std::vector<std::uint8_t>& dst, int width, int height, int x0,
              int y0, int x1, int y1) {
  fill_rect(dst, width, height, x0, y0, x1,
            std::min(y0 + kBoxThickness - 1, y1), kBoxColor);
  fill_rect(dst, width, height, x0, std::max(y1 - kBoxThickness + 1, y0), x1,
            y1, kBoxColor);
  fill_rect(dst, width, height, x0, y0,
            std::min(x0 + kBoxThickness - 1, x1), y1, kBoxColor);
  fill_rect(dst, width, height, std::max(x1 - kBoxThickness + 1, x0), y0, x1,
            y1, kBoxColor);
}

std::string label_text(const TargetBox& target) {
  char score[16];
  std::snprintf(score, sizeof(score), "%.2f", static_cast<double>(target.score));
  std::string text = target.label;
  if (!text.empty()) {
    text.push_back(' ');
  }
  text += score;
  return text;
}

void draw_label(std::vector<std::uint8_t>& dst, int width, int height, int box_x,
                int box_y, const std::string& text) {
  if (text.empty()) {
    return;
  }

  const int text_width = static_cast<int>(text.size()) * kGlyphWidth;
  int x = box_x;
  if (x + text_width > width) {
    x = width - text_width;
  }
  x = std::max(x, 0);

  int y = box_y - kGlyphHeight;
  if (y < 0) {
    y = box_y;
  }
  if (y + kGlyphHeight > height) {
    y = height - kGlyphHeight;
  }
  y = std::max(y, 0);

  for (std::size_t i = 0; i < text.size(); ++i) {
    const std::uint8_t* glyph = glyph_for(text[i]);
    const int glyph_x = x + static_cast<int>(i) * kGlyphWidth;
    if (glyph_x >= width) {
      break;
    }
    for (int row = 0; row < kGlyphHeight; ++row) {
      const std::uint8_t bits = glyph[row];
      for (int col = 0; col < kGlyphWidth; ++col) {
        if ((bits >> col) & 1u) {
          put_pixel(dst, width, height, glyph_x + col, y + row, kLabelColor);
        }
      }
    }
  }
}

