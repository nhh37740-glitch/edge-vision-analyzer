void draw_osd(const FrameMeta& src, const std::vector<TargetBox>& targets,
              std::vector<std::uint8_t>& dst) {
  if (src.width <= 0 || src.height <= 0) {
    return;
  }

  for (const TargetBox& target : targets) {
    float x = target.x;
    float y = target.y;
    float w = target.w;
    float h = target.h;
    if (w < 0.0f) {
      x += w;
      w = -w;
    }
    if (h < 0.0f) {
      y += h;
      h = -h;
    }

    // Keep the conversion well-defined for wildly out-of-range inputs while
    // preserving whether a box lies entirely outside the frame.
    x = std::max(-1.0f, std::min(x, 2.0f));
    y = std::max(-1.0f, std::min(y, 2.0f));
    w = std::max(0.0f, std::min(w, 3.0f));
    h = std::max(0.0f, std::min(h, 3.0f));

    const int x0 = static_cast<int>(std::floor(x * src.width));
    const int y0 = static_cast<int>(std::floor(y * src.height));
    const int x1 = static_cast<int>(std::ceil((x + w) * src.width)) - 1;
    const int y1 = static_cast<int>(std::ceil((y + h) * src.height)) - 1;
    if (x1 < 0 || y1 < 0 || x0 >= src.width || y0 >= src.height) {
      continue;
    }

    const int clipped_x0 = std::max(x0, 0);
    const int clipped_y0 = std::max(y0, 0);
    const int clipped_x1 = std::min(x1, src.width - 1);
    const int clipped_y1 = std::min(y1, src.height - 1);
    if (clipped_x1 < clipped_x0 || clipped_y1 < clipped_y0) {
      continue;
    }

    draw_box(dst, src.width, src.height, clipped_x0, clipped_y0, clipped_x1,
             clipped_y1);
    draw_label(dst, src.width, src.height, clipped_x0, clipped_y0,
               label_text(target));
  }
}

